import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { Platform } from 'react-native';
import { showToast } from './toast';

/**
 * Exports a scan result as a PDF file.
 * On mobile: opens native share sheet with the generated PDF.
 * On web: opens the browser print dialog (user can "Save as PDF" from there).
 *
 * @param {{ mode: string, extractedText: string, analysis: string, savedAt?: string, timestamp?: string }} scan
 * @returns {Promise<boolean>} true if export succeeded
 */
export async function exportScanAsPDF(scan) {
  if (!scan) {
    showToast('No scan data to export');
    return false;
  }

  try {
    const dateStr = new Date(scan.savedAt || scan.timestamp || Date.now()).toLocaleString();

    const htmlContent = `
      <html>
        <head>
          <meta charset="utf-8" />
          <style>
            body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; padding: 40px; color: #333; }
            h1 { color: #4A1117; font-size: 24px; border-bottom: 2px solid #4A1117; padding-bottom: 8px; }
            .mode-badge { display: inline-block; background: #E8D5D5; padding: 4px 14px; border-radius: 12px; font-weight: 600; font-size: 13px; color: #4A1117; margin-bottom: 16px; }
            .section { margin-bottom: 24px; }
            .section-title { font-size: 14px; font-weight: 700; color: #585858; text-transform: uppercase; letter-spacing: 0.5px; margin-bottom: 8px; }
            .content-box { background: #f9f9f9; border: 1px solid #e0e0e0; border-radius: 8px; padding: 16px; white-space: pre-wrap; line-height: 1.6; font-size: 14px; }
            .timestamp { font-size: 12px; color: #585858; font-style: italic; margin-top: 24px; }
            .footer { margin-top: 40px; border-top: 1px solid #e0e0e0; padding-top: 12px; font-size: 11px; color: #999; text-align: center; }
          </style>
        </head>
        <body>
          <h1>ContextCam Scan Report</h1>
          <div class="mode-badge">${escapeHtml(scan.mode || 'HEALTH')}</div>
          
          <div class="section">
            <div class="section-title">Extracted Text</div>
            <div class="content-box">${escapeHtml(scan.extractedText || 'No text extracted')}</div>
          </div>
          
          <div class="section">
            <div class="section-title">Contextual Analysis</div>
            <div class="content-box">${escapeHtml(scan.analysis || 'No analysis available')}</div>
          </div>
          
          <div class="timestamp">Captured on ${escapeHtml(dateStr)}</div>
          <div class="footer">Generated by ContextCam</div>
        </body>
      </html>
    `;

    if (Platform.OS === 'web') {
      // On web, printToFileAsync may not produce a downloadable file,
      // so use printAsync which opens the browser's print dialog (user can "Save as PDF")
      await Print.printAsync({ html: htmlContent });
      showToast('PDF sent to print dialog');
      return true;
    }

    // On mobile, generate a PDF file and share it
    const { uri } = await Print.printToFileAsync({ html: htmlContent });

    const sharingAvailable = await Sharing.isAvailableAsync();
    if (sharingAvailable) {
      await Sharing.shareAsync(uri, {
        mimeType: 'application/pdf',
        dialogTitle: 'Export ContextCam Scan',
        UTI: 'com.adobe.pdf',
      });
      showToast('PDF exported successfully');
      return true;
    } else {
      showToast('Sharing is not available on this device');
      return false;
    }
  } catch (error) {
    if (__DEV__) {
      console.error('[PDF Export Error]:', error);
    }
    showToast('Failed to export PDF: ' + (error?.message || 'Unknown error'));
    return false;
  }
}

function escapeHtml(str) {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}
